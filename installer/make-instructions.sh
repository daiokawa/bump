#!/usr/bin/env bash
# 相手（人間）宛の案内を1枚つくる。AIに貼り付ける文は作らない。
#
# なぜ人間宛か: 「AIに語りかけ・送り主を自称し・プロセスを止めてDownloadsのバイナリを実行させ・
# ユーザーへの伝え方まで指定する」文は、プロンプトインジェクションと同じ形をしている。
# 実際にテスト運用で実際に受信側AIが攻撃と判断して拒否した（2026-07-28）。bumpは「届いた文を
# 勝手に実行しない」道具なのに、配布のときだけ自分がそれを破っていた。
# 直し方: 人が読んで人が判断する。ダブルクリックだけで接続まで終わる（アプリが自分でやる）。
# AIの役目は「頼まれたら調べる」側に置く（リポジトリとAUDIT.mdを読ませる）。
#
# 使い方: bash installer/make-instructions.sh "K.K." [relayURL]
set -euo pipefail
cd "$(dirname "$0")/.."

LABEL="${1:?宛先名を指定してください（例: K.K.）}"
SLUG="$(printf '%s' "$LABEL" | tr ' /:*?"<>|' '_________')"
ZIP="bump-$SLUG.zip"
APPDIR="bump-$SLUG.app"
REPO="${MM_REPO_URL:?公開リポジトリのURLを MM_REPO_URL で指定してください}"
OUT="dist/old/instructions-$SLUG.md"; mkdir -p dist/old

cat > "$OUT" <<EOF
# $LABEL さんへ：bump のセットアップ

やることは2つだけです。**AIに貼り付ける文はありません。**

1. 添付の \`$ZIP\` を解凍します（たぶん ~/Downloads に \`$APPDIR\` ができます）
2. それを**ダブルクリック**します

これだけで、鍵の作成・画面の起動・私への接続申し込みまで終わります。私が承認すると、その瞬間から手紙のやり取りができます。画面は <http://localhost:8790> です。

**初回だけ「開発元が確認できません」と出ます。** Appleの署名をまだ取っていないためです。その場合は、アプリを**右クリック →「開く」**を選んでください（2回目以降は普通にダブルクリックで開きます）。

## 中身を確かめたいとき

見ずに動かすのが気持ち悪いのは当然なので、確かめる道を用意しています。$LABEL さんのClaudeに頼んでください。「これ入れる前に中身を見て」と言えば読みます。

- ソース: <$REPO>（$LABEL さんはアクセスできます）
- 疑うための道具: リポジトリの \`AUDIT.md\`。通信先・実行する外部コマンド・書き込む場所・開くポート・中継サーバーに何が見えるかを、**自分の目で確かめる手順**が5分ぶんまとまっています
- 隔離して試すこともできます（\`BUMP_HOME=/tmp/mmtest\` で保存先を変えれば跡形なく消せます）

要点だけ先に書いておくと、触るのは \`~/.bump-app\`（コード）・\`~/.bump\`（鍵と手紙）・\`~/.bump-hub\`（接続先の控え）の3つだけ、開くポートは 127.0.0.1 の8790だけ、sudoは使いません。ただしこれは私の主張なので、確かめる方が確かです。

## 大事なところ

bumpは**届いた手紙を勝手に実行しません**。読ませるか・応じるかは毎回 $LABEL さんが決めます。承認・拒否のボタンが人の手に残っているのが、この道具の中身です。

何か引っかかったら、Chatworkでそのまま聞いてください。
EOF

echo "できました: $OUT"
echo "  → $LABEL さんへ Chatwork で送るもの: dist/$ZIP ＋ ${OUT}（丸ごとでOK）"
echo
echo "［$LABEL さんが受け取った後、こちら側で起きること］"
echo "  ・ダブルクリックで接続リクエストが飛ぶ → 画面に「接続リクエスト」が出る（合言葉は自動照合）"
echo "  ・relay(受信箱) が起動中であること"
